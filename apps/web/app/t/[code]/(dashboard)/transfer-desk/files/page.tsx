"use client";

/**
 * Transfer Desk — File Repository (UI-URL-018 / UI-PAGE-011)
 *
 * S3-backed file folder hierarchy. Profiles read from / write to these folders
 * via the `transfer_folders`, `transfer_folder_access`, and `transfer_files`
 * tables (Module 7 of the Transfer Desk Technical Spec).
 *
 * STUB: backend tables and endpoints (TD-DB-016..018, TD-API-063..070) are
 * not yet implemented. This page renders the spec layout with placeholder
 * folder structure and a disabled upload button so the wizard's "select
 * file from repository" step has somewhere to link to.
 */

import Link from "next/link";
import { useState } from "react";
import { useUserRole } from "../../../../../../components/use-user-role";
import { useTenantHref } from "../../../../../../hooks/use-tenant-router";
import { Card, CardContent } from "../../../../../../components/ui/card";
import { Badge } from "../../../../../../components/ui/badge";
import { Button } from "../../../../../../components/ui/button";
import {
  Folder,
  FolderOpen,
  FileText,
  Upload,
  Download,
  Lock,
  ChevronRight,
  ArrowLeft,
  AlertTriangle
} from "lucide-react";

type FolderNode = {
  id: string;
  name: string;
  description?: string;
  children?: FolderNode[];
};

// Placeholder folder tree mirroring the spec example. When the backend ships,
// this is replaced by a fetch of GET /api/v1/integration/transfer-desk/folders.
const PLACEHOLDER_TREE: FolderNode[] = [
  {
    id: "inbox",
    name: "Inbox",
    description: "Files received from external systems waiting for import",
    children: [
      { id: "inbox/opera", name: "Opera PMS" },
      { id: "inbox/jana", name: "Sky Jana" },
      { id: "inbox/bank", name: "Bank Statements" }
    ]
  },
  {
    id: "outbox",
    name: "Outbox",
    description: "Files generated by export profiles waiting for pickup",
    children: [
      { id: "outbox/payments", name: "Payment Files" },
      { id: "outbox/reports", name: "Reports" }
    ]
  },
  {
    id: "archive",
    name: "Archive",
    description: "Imported files moved here after successful processing",
    children: []
  }
];

export default function FilesPage() {
  const tenantHref = useTenantHref();
  const role = useUserRole();
  const [selectedFolderId, setSelectedFolderId] = useState<string>("inbox");

  if (!role.canTransferDeskUser) {
    return (
      <div className="flex flex-col items-center justify-center min-h-[60vh] gap-3 p-6 text-center">
        <Lock className="h-10 w-10 text-slate-300" />
        <h2 className="text-lg font-semibold text-slate-700">Access required</h2>
        <p className="text-sm text-slate-500 max-w-md">
          You need at least the <code className="font-mono">transfer:user</code> role to browse the
          file repository.
        </p>
      </div>
    );
  }

  const flatFolders = (function flatten(
    nodes: FolderNode[],
    depth = 0
  ): Array<FolderNode & { depth: number }> {
    const out: Array<FolderNode & { depth: number }> = [];
    for (const n of nodes) {
      out.push({ ...n, depth });
      if (n.children?.length) out.push(...flatten(n.children, depth + 1));
    }
    return out;
  })(PLACEHOLDER_TREE);

  const selected = flatFolders.find((f) => f.id === selectedFolderId);

  return (
    <div className="p-6 max-w-7xl mx-auto space-y-4">
      {/* Breadcrumb back to landing */}
      <Link
        href={tenantHref("/transfer-desk")}
        className="inline-flex items-center gap-1.5 text-xs text-slate-500 hover:text-emerald-600"
      >
        <ArrowLeft className="h-3.5 w-3.5" /> Back to Transfer Desk
      </Link>

      {/* Header */}
      <div className="flex items-start justify-between gap-4">
        <div>
          <h1 className="text-2xl font-semibold text-(--color-primary) flex items-center gap-2">
            <FolderOpen className="h-5 w-5" /> File Repository
          </h1>
          <p className="text-sm text-slate-500 mt-1">
            Browse files staged for import, generated by exports, or moved to archive.
          </p>
        </div>
        <Button variant="teal" size="sm" disabled className="gap-1.5" title="Coming soon">
          <Upload className="h-3.5 w-3.5" /> Upload File
        </Button>
      </div>

      {/* MVP stub notice */}
      <div className="rounded-xl border border-amber-200 bg-amber-50 px-4 py-3 text-xs text-amber-900 flex items-start gap-2">
        <AlertTriangle className="h-3.5 w-3.5 mt-0.5 shrink-0" />
        <div>
          <p className="font-semibold">Stub view — backend not yet implemented</p>
          <p className="mt-0.5">
            The file repository tables (TD-DB-016..018) and S3-backed endpoints (TD-API-063..070)
            are scheduled for sprint 11 of the implementation roadmap. The folder tree and file list
            shown below are placeholder data.
          </p>
        </div>
      </div>

      {/* Two-pane layout: folder tree + file list */}
      <div className="flex gap-4 min-h-[400px]">
        {/* ── Folder tree (left) ─────────────────────────────────────────── */}
        <Card className="w-64 shrink-0">
          <CardContent className="p-2 space-y-0.5">
            {flatFolders.map((folder) => {
              const isSelected = folder.id === selectedFolderId;
              return (
                <button
                  key={folder.id}
                  type="button"
                  onClick={() => setSelectedFolderId(folder.id)}
                  className={`w-full flex items-center gap-2 px-2 py-1.5 rounded-lg text-left text-sm transition-colors ${
                    isSelected
                      ? "bg-emerald-50 text-emerald-700 font-medium"
                      : "text-slate-600 hover:bg-slate-50"
                  }`}
                  style={{ paddingLeft: 8 + folder.depth * 16 }}
                >
                  {folder.children?.length ? (
                    <ChevronRight className="h-3 w-3 text-slate-400 shrink-0" />
                  ) : (
                    <span className="w-3 shrink-0" />
                  )}
                  {isSelected ? (
                    <FolderOpen className="h-4 w-4 text-emerald-600 shrink-0" />
                  ) : (
                    <Folder className="h-4 w-4 text-slate-400 shrink-0" />
                  )}
                  <span className="truncate">{folder.name}</span>
                </button>
              );
            })}
          </CardContent>
        </Card>

        {/* ── File list (main) ───────────────────────────────────────────── */}
        <Card className="flex-1 min-w-0">
          <CardContent className="p-0">
            {/* Folder header */}
            <div className="px-4 py-3 border-b border-slate-100">
              <h2 className="text-sm font-semibold text-slate-800">{selected?.name ?? "—"}</h2>
              {selected?.description && (
                <p className="text-xs text-slate-500 mt-0.5">{selected.description}</p>
              )}
            </div>
            {/* Empty file list */}
            <div className="text-center py-16 text-sm text-slate-400">
              <FileText className="h-10 w-10 mx-auto mb-3 text-slate-200" />
              <p>No files in this folder.</p>
              <p className="text-xs mt-1">
                Files will appear here once the backend repository is wired up and uploads are
                enabled.
              </p>
              {role.canTransferDeskAdmin && (
                <Badge variant="secondary" className="mt-3 text-[10px]">
                  Admins will see upload + delete here
                </Badge>
              )}
            </div>
          </CardContent>
        </Card>
      </div>
    </div>
  );
}
